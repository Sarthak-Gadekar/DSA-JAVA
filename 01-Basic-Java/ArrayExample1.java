class ArrayExample1
{
    public static void main(String[] args)
	{
		// declare and initialize an array
		
        int[] arr = {10, 20, 30, 40, 50};
		
        System.out.println("Array Elements:");
		
        for(int i = 0; i < arr.length; i++)
		{
            System.out.println(arr[i]);
        }
    }
}