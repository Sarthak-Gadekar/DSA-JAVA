class AssignmentOperators
{
	public static void main(String arg[])
	{
		int a = 10;
		System.out.println("Initial Value "+a);
		
		a+=5;
		System.out.println("After Addition: "+a);
		
		a-=3;
		System.out.println("After Subtraction: "+a);
		
		a*=2;
		System.out.println("After Multiplication: "+a);
		
		a/=4;
		System.out.println("After Division: "+a);
		
		a%=3;
		System.out.println("After Modulus: "+a);
		
	}
}